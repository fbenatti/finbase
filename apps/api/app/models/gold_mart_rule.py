"""Regra de cubo Gold — pré-agregação de custo materializada a partir da Silver.

A Gold rule selects one or more sources. Each source points at ONE OR MORE
Gold tables with the same normalized structure (e.g. dest_modelo_focus and
dest_modelo_focus_planning). The tables of a source are unioned together
(same filters applied on each) into a single clean dataset, then aggregated.
"""

from sqlalchemy import (
    Column, Integer, String, DateTime, JSON, Boolean, Float, Text, ForeignKey, func, Index,
)
from sqlalchemy.orm import relationship
from app.database import Base

VALUE_COLUMNS = frozenset({"realizado", "BilledCost", "EffectiveCost"})


class GoldMartRule(Base):
    """Uma regra de cubo Gold: fontes + filtros -> dest_dm_cost_<code>."""
    __tablename__ = "gold_rule"

    id = Column(Integer, primary_key=True, autoincrement=True)
    # Human-friendly unique slug that names the materialized table:
    # dest_dm_cost_<code>. Kept as typed by the user (slug-safe validated).
    code = Column(String(120), nullable=False, unique=True, index=True)
    name = Column(String(200), nullable=False)
    description = Column(Text, nullable=True)
    active = Column(Boolean, nullable=False, default=True)
    valid_from = Column(String(6), nullable=True)
    valid_until = Column(String(6), nullable=True)
    # GROUP BY dimensions for the pre-aggregation. Empty/None -> analytic
    # default (period + dept hierarchy + cloud + service + category + tipo).
    dimensions = Column(JSON, nullable=False, default=list)
    # Measure columns to SUM (e.g. ["realizado", "billedcost"]). Empty ->
    # the source value_column (realizado). Pivot-style multi-measure support.
    measure_columns = Column(JSON, nullable=False, default=list)
    # Materialized Gold table generated by the relationship job.
    materialization_table = Column(String(140), nullable=True)
    materialization_status = Column(String(30), nullable=False, default="PENDING", server_default="PENDING")
    materialization_rows = Column(Integer, nullable=True)
    materialization_run_id = Column(Integer, nullable=True)
    materialized_at = Column(DateTime(timezone=True), nullable=True)
    materialization_error = Column(Text, nullable=True)
    # SQL custom (optional): when present, bypasses the pivot builder and uses
    # this query to materialize the Gold table. The query MUST produce a result
    # named with the same dimensions + measures the UI expects.
    sql_template = Column(Text, nullable=True)
    # Snapshot mode: quando ativo, a materialização NÃO substitui a tabela;
    # adiciona uma cópia datada (coluna _snapshot_date) preservando o histórico,
    # permitindo comparar snapshots (ex.: delta de tags shutdown=auto entre dias).
    snapshot_mode = Column(Boolean, nullable=False, default=False)
    snapshot_col = Column(String(50), nullable=False, default="_snapshot_date")
    created_at = Column(DateTime(timezone=True), server_default=func.now())
    updated_at = Column(DateTime(timezone=True), server_default=func.now(), onupdate=func.now())

    sources = relationship(
        "GoldMartRuleSource",
        cascade="all, delete-orphan",
        passive_deletes=True,
        lazy="selectin",
        order_by="GoldMartRuleSource.id",
    )


class GoldMartRuleSource(Base):
    """Uma fonte que contribui linhas para o cubo Gold.

    A source binds one or more Gold tables with the same normalized structure
    (e.g. dest_modelo_focus + dest_modelo_focus_planning). Filters, value
    column and percent apply to every table in the source; the tables are
    unioned into a single clean dataset before aggregation.
    """
    __tablename__ = "gold_rule_source"
    __table_args__ = (Index("ix_gold_rule_source_rule", "rule_id"),)

    id = Column(Integer, primary_key=True, autoincrement=True)
    rule_id = Column(Integer, ForeignKey("gold_rule.id", ondelete="CASCADE"), nullable=False)
    # Legacy single-table column kept for compatibility; gold_tables is the
    # source of truth and always contains at least one physical name.
    gold_table = Column(String(140), nullable=False)
    # One or more Gold table physical names with the same structure.
    gold_tables = Column(JSON, nullable=False, default=list)
    filter_json = Column(JSON, nullable=False, default=dict)
    value_column = Column(String(50), nullable=False, default="realizado")
    percent = Column(Float, nullable=False, default=100.0)
    created_at = Column(DateTime(timezone=True), server_default=func.now())

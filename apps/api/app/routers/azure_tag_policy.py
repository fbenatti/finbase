"""
Azure Tag Policy router — expose the generated Azure Policy documents and
deployment scripts (per tenant) for the "Criação de Tags" tab.

Endpoints:
  GET /azure-tag-policy/tenants   — list Azure source connections (tenants)
  GET /azure-tag-policy/export    — generate policies + deployment script
"""

from __future__ import annotations

import json

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import PlainTextResponse, JSONResponse
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.services.azure_tag_policy_service import AzureTagPolicyService, slugify

router = APIRouter(prefix="/azure-tag-policy", tags=["azure-tag-policy"])


@router.get("/tenants")
async def list_tenants(db: AsyncSession = Depends(get_db)):
    service = AzureTagPolicyService(db)
    return await service.list_azure_tenants()


@router.get("/export")
async def export_policy(
    connection_id: int | None = Query(None, description="Optional: a single Azure connection/tenant"),
    fmt: str = Query("json", description="Output format: json | script | both"),
    db: AsyncSession = Depends(get_db),
):
    service = AzureTagPolicyService(db)

    tenants = await service.list_azure_tenants()
    if not tenants:
        raise HTTPException(status_code=404, detail="Nenhum tenant Azure configurado")

    selected = tenants
    if connection_id is not None:
        selected = [t for t in tenants if t["connection_id"] == connection_id]
        if not selected:
            raise HTTPException(status_code=404, detail="Tenant Azure não encontrado")

    policies = []
    for tenant in selected:
        doc = await service.generate_tenant_policy(tenant["connection_id"])
        if doc:
            policies.append(doc)

    if fmt in ("script", "both"):
        script = build_script(policies)
    else:
        script = ""

    if fmt == "script":
        return PlainTextResponse(script, media_type="text/x-shellscript")

    payload = {
        "tenants": policies,
        "deployment_script": script,
    }
    return JSONResponse(payload)


def build_script(policies: list[dict]) -> str:
    """Build an `az` CLI script (assignments + remediation tasks) for all tenants."""
    lines: list[str] = []
    lines.append("#!/usr/bin/env bash")
    lines.append("# Azure Policy deployment script generated by OpenFinops")
    lines.append("# Applies tag policies (departamento_nivel_*, centro_custo, ambiente)")
    lines.append('set -euo pipefail')
    lines.append("")
    lines.append("# The management-group or subscription scope must be supplied by the operator.")
    lines.append('SCOPE="${SCOPE:-/providers/Microsoft.Management/managementGroups/<your-mg>}"')
    lines.append('LOCATION="${LOCATION:-eastus2}"')
    lines.append("")

    for tenant in policies:
        lines.append("#")
        lines.append(f"# ── Tenant: {tenant.get('connection_name')} ({tenant.get('connection_code')}) ──")
        lines.append(f"# Tenant ID: {tenant.get('tenant_id')}")
        lines.append("#")

        layers = tenant.get("layers", {})

        # 1. Inheritance
        lines.append("# 1. Resource-group inheritance (built-in)")
        for inherit in layers.get("inheritance", []):
            tag = inherit["parameters"]["tagName"]["value"]
            name = f"openfinops-inherit-{slugify(tag)}"
            lines.append(f"az policy assignment create --name {name} \\")
            lines.append(f"  --scope \"$SCOPE\" \\")
            lines.append(f"  --policy \"{inherit['policyDefinitionId']}\" \\")
            lines.append(f"  --params tagName=\\'{tag}\\'")
            lines.append("")

        # 2. Resource-group explicit lists (grouped)
        lines.append("# 2. Resource-group tag application (grouped by unique tag set)")
        lines.append("POLICIES_DIR=$(mktemp -d)")
        for i, rg in enumerate(layers.get("resource_groups", []), start=1):
            policy_json = _rg_policy_json(rg)
            def_name = f"openfinops-rg-{slugify(tenant.get('connection_code'))}-{i}"
            lines.append(f"cat > \"$POLICIES_DIR/{def_name}.json\" <<'POLICYEOF'")
            lines.append(json.dumps(policy_json, indent=2, ensure_ascii=False))
            lines.append("POLICYEOF")
            lines.append(f"az policy definition create --name {def_name} \\")
            lines.append(f"  --mode Indexed --rules \"$POLICIES_DIR/{def_name}.json\"")
            lines.append(f"az policy assignment create --name {def_name} \\")
            lines.append(f"  --scope \"$SCOPE\" --policy {def_name}")
            lines.append("")

        # 3. Pattern policies (name / SKU / region)
        lines.append("# 3. Pattern policies (name / SKU family / region)")
        for i, pat in enumerate(layers.get("patterns", []), start=1):
            def_name = f"openfinops-pattern-{slugify(tenant.get('connection_code'))}-{i}"
            policy_json = _pattern_policy_json(pat)
            lines.append(f"cat > \"$POLICIES_DIR/{def_name}.json\" <<'POLICYEOF'")
            lines.append(json.dumps(policy_json, indent=2, ensure_ascii=False))
            lines.append("POLICYEOF")
            lines.append(f"az policy definition create --name {def_name} \\")
            lines.append(f"  --mode Indexed --rules \"$POLICIES_DIR/{def_name}.json\"")
            lines.append(f"az policy assignment create --name {def_name} \\")
            lines.append(f"  --scope \"$SCOPE\" --policy {def_name}")
            lines.append("")

        # 4. Remediation tasks
        lines.append("# 4. Remediation tasks (existing resources)")
        rg_defs = len(layers.get("resource_groups", []))
        pat_defs = len(layers.get("patterns", []))
        for i in range(1, rg_defs + 1):
            name = f"openfinops-rg-{slugify(tenant.get('connection_code'))}-{i}"
            lines.append(f"az policy remediation create --name remediate-{name} \\")
            lines.append(f"  --policy-assignment {name} --resource-discovery-mode ReEvaluateCompliance")
        for i in range(1, pat_defs + 1):
            name = f"openfinops-pattern-{slugify(tenant.get('connection_code'))}-{i}"
            lines.append(f"az policy remediation create --name remediate-{name} \\")
            lines.append(f"  --policy-assignment {name} --resource-discovery-mode ReEvaluateCompliance")
        lines.append("")

    lines.append("# Done. Resource-group inheritance remediation:")
    lines.append("#   az policy remediation create \\")
    lines.append("#     --name remediate-inherit --policy-assignment openfinops-inherit-departamento-nivel-1 \\")
    lines.append('#     --resource-discovery-mode ReEvaluateCompliance')
    lines.append("")

    return "\n".join(lines)


def _rg_policy_json(rg: dict) -> dict:
    names = rg.get("names", [])
    tags = rg.get("tags", {})
    operations = [
        {"operation": "addOrReplace", "field": f"tags['{k}']", "value": v}
        for k, v in tags.items() if v
    ]
    name_condition = {"field": "name", "in": names} if len(names) > 1 else {"field": "name", "equals": names[0]}
    return {
        "mode": "Indexed",
        "policyRule": {
            "if": {
                "allOf": [
                    {"field": "type", "equals": "Microsoft.Resources/resourceGroups"},
                    name_condition,
                ]
            },
            "then": {
                "effect": "modify",
                "details": {
                    "roleDefinitionIds": [
                        "/providers/microsoft.authorization/roleDefinitions/b24988ac-6180-42a0-ab88-20f7382dd24c",
                    ],
                    "operations": operations,
                },
            },
        },
    }


def _pattern_policy_json(pat: dict) -> dict:
    tags = pat.get("tags", {})
    condition = pat.get("condition", {})
    operations = [
        {"operation": "addOrReplace", "field": f"tags['{k}']", "value": v}
        for k, v in tags.items() if v
    ]
    return {
        "mode": "Indexed",
        "policyRule": {
            "if": condition,
            "then": {
                "effect": "modify",
                "details": {
                    "roleDefinitionIds": [
                        "/providers/microsoft.authorization/roleDefinitions/b24988ac-6180-42a0-ab88-20f7382dd24c",
                    ],
                    "operations": operations,
                },
            },
        },
    }

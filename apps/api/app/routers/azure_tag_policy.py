"""
Azure Tag Policy router — expose the generated Azure Policy documents and
deployment scripts (per tenant) for the "Criação de Tags" tab.

Endpoints:
  GET /azure-tag-policy/tenants   — list Azure source connections (tenants)
  GET /azure-tag-policy/export    — generate policies + deployment script
"""

from __future__ import annotations

import json
import logging
from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Query
from fastapi.responses import PlainTextResponse, JSONResponse
from sqlalchemy.ext.asyncio import AsyncSession

from app.database import get_db
from app.services.azure_tag_policy_service import AzureTagPolicyService, slugify

logger = logging.getLogger("openfinops.azure_tag_policy")

router = APIRouter(prefix="/azure-tag-policy", tags=["azure-tag-policy"])


@router.get("/tenants")
async def list_tenants(db: AsyncSession = Depends(get_db)):
    service = AzureTagPolicyService(db)
    return await service.list_azure_tenants()


@router.get("/export")
async def export_policy(
    connection_id: int | None = Query(None, description="Optional: a single Azure connection/tenant"),
    fmt: str = Query("json", description="Output format: json | script | both"),
    db: AsyncSession = Depends(get_db),
):
    service = AzureTagPolicyService(db)

    tenants = await service.list_azure_tenants()
    if not tenants:
        raise HTTPException(status_code=404, detail="Nenhum tenant Azure configurado")

    selected = tenants
    if connection_id is not None:
        selected = [t for t in tenants if t["connection_id"] == connection_id]
        if not selected:
            raise HTTPException(status_code=404, detail="Tenant Azure não encontrado")

    policies = []
    for tenant in selected:
        doc = await service.generate_tenant_policy(tenant["connection_id"])
        if doc:
            policies.append(doc)

    if fmt in ("script", "both"):
        script = build_script(policies)
    else:
        script = ""

    if fmt == "script":
        return PlainTextResponse(script, media_type="text/x-shellscript")

    payload = {
        "tenants": policies,
        "deployment_script": script,
    }
    return JSONResponse(payload)


def build_script(policies: list[dict]) -> str:
    """Build an `az` CLI deployment script for all tenants."""
    lines: list[str] = []
    lines.append("#!/usr/bin/env bash")
    lines.append("# Azure Policy deployment script generated by OpenFinops")
    lines.append("# Applies tag policies (departamento_nivel_*, centro_custo, ambiente)")
    lines.append("set -euo pipefail")
    lines.append("")
    lines.append("# Escopo de Management Group ou Subscription (deve ser definido pelo operador):")
    lines.append('SCOPE="${SCOPE:-/providers/Microsoft.Management/managementGroups/<your-mg>}"')
    lines.append('LOCATION="${LOCATION:-eastus2}"')
    lines.append("")
    lines.append('echo "[INFO] Iniciando implantação das Políticas de Tag do OpenFinops..."')
    lines.append('echo "[INFO] Escopo configurado: $SCOPE"')
    lines.append("")

    for tenant in policies:
        conn_code = tenant.get("connection_code", "azure")
        conn_name = tenant.get("connection_name", "Azure Tenant")
        tenant_id = tenant.get("tenant_id", "")
        slug_code = slugify(conn_code)

        lines.append("# " + "=" * 70)
        lines.append(f"# Tenant: {conn_name} ({conn_code})")
        lines.append(f"# Tenant ID: {tenant_id}")
        lines.append("# " + "=" * 70)
        lines.append(f'echo "[INFO] Processando tenant: {conn_name} ({conn_code})..."')
        lines.append("")

        layers = tenant.get("layers", {})

        # 1. Inheritance Built-in Policies
        lines.append("# ------------------------------------------------------------------------------")
        lines.append("# 1. Herança de Tags do Resource Group para Recursos Filhos (Built-in Policy)")
        lines.append("# ------------------------------------------------------------------------------")
        for inherit in layers.get("inheritance", []):
            tag = inherit["parameters"]["tagName"]["value"]
            name = f"openfinops-inherit-{slugify(tag)}"
            lines.append(f'echo "[INFO] Criando atribuição de herança para a tag: {tag}..."')
            lines.append(f"az policy assignment create --name {name} \\")
            lines.append(f'  --scope "$SCOPE" \\')
            lines.append(f"  --policy \"{inherit['policyDefinitionId']}\" \\")
            lines.append(f"  --params tagName=\\'{tag}\\' --only-show-errors")
            lines.append("")

        lines.append("POLICIES_DIR=$(mktemp -d)")
        lines.append('echo "[INFO] Diretório temporário de definições: $POLICIES_DIR"')
        lines.append("")

        # 2. Resource Groups agrupados por lista exata
        rgs_exact = layers.get("resource_groups", [])
        if rgs_exact:
            lines.append("# ------------------------------------------------------------------------------")
            lines.append("# 2. Políticas de Resource Groups Exatos (agrupados por tag idêntica)")
            lines.append("# ------------------------------------------------------------------------------")
            for i, rg in enumerate(rgs_exact, start=1):
                def_name = f"openfinops-rg-{slug_code}-{i}"
                policy_json = _build_policy_definition(
                    display_name=f"OpenFinops - Tag RG Group {i} ({conn_code})",
                    description=f"Aplica tags organizacionais nos Resource Groups: {', '.join(rg.get('names', [])[:5])}",
                    if_condition=rg.get("condition", {}),
                    tags=rg.get("tags", {}),
                )
                lines.append(f'echo "[INFO] Criando definição de política para grupo de RGs: {def_name}..."')
                lines.append(f'cat > "$POLICIES_DIR/{def_name}.json" <<\'POLICYEOF\'')
                lines.append(json.dumps(policy_json, indent=2, ensure_ascii=False))
                lines.append("POLICYEOF")
                lines.append(f"az policy definition create --name {def_name} \\")
                lines.append(f'  --mode Indexed --rules "$POLICIES_DIR/{def_name}.json" --only-show-errors')
                lines.append(f"az policy assignment create --name {def_name} \\")
                lines.append(f'  --scope "$SCOPE" --policy {def_name} --only-show-errors')
                lines.append("")

        # 3. Resource Groups por Nomenclatura / Padrão (Wildcard)
        rgs_patterns = layers.get("rg_patterns", [])
        if rgs_patterns:
            lines.append("# ------------------------------------------------------------------------------")
            lines.append("# 3. Políticas de Resource Groups por Nomenclatura / Padrão (~)")
            lines.append("# ------------------------------------------------------------------------------")
            for i, pat in enumerate(rgs_patterns, start=1):
                def_name = f"openfinops-rgpat-{slug_code}-{i}"
                patterns_str = ", ".join(pat.get("patterns", []))
                policy_json = _build_policy_definition(
                    display_name=f"OpenFinops - Tag RG Pattern {patterns_str} ({conn_code})",
                    description=f"Aplica tags nos RGs que atendem ao padrão de nomenclatura: {patterns_str}",
                    if_condition=pat.get("condition", {}),
                    tags=pat.get("tags", {}),
                )
                lines.append(f'echo "[INFO] Criando definição de política para RG pattern: {def_name}..."')
                lines.append(f'cat > "$POLICIES_DIR/{def_name}.json" <<\'POLICYEOF\'')
                lines.append(json.dumps(policy_json, indent=2, ensure_ascii=False))
                lines.append("POLICYEOF")
                lines.append(f"az policy definition create --name {def_name} \\")
                lines.append(f'  --mode Indexed --rules "$POLICIES_DIR/{def_name}.json" --only-show-errors')
                lines.append(f"az policy assignment create --name {def_name} \\")
                lines.append(f'  --scope "$SCOPE" --policy {def_name} --only-show-errors')
                lines.append("")

        # 4. Políticas de Recursos Individuais, SKUs, Tipos e Regiões
        res_patterns = layers.get("patterns", [])
        if res_patterns:
            lines.append("# ------------------------------------------------------------------------------")
            lines.append("# 4. Políticas de Recursos Individuais, SKUs e Tipos")
            lines.append("# ------------------------------------------------------------------------------")
            for i, pat in enumerate(res_patterns, start=1):
                def_name = f"openfinops-respat-{slug_code}-{i}"
                policy_json = _build_policy_definition(
                    display_name=f"OpenFinops - Tag Resource Pattern {i} ({conn_code})",
                    description="Aplica tags em recursos individuais conforme condições de classificação",
                    if_condition=pat.get("condition", {}),
                    tags=pat.get("tags", {}),
                )
                lines.append(f'echo "[INFO] Criando definição de política para recurso: {def_name}..."')
                lines.append(f'cat > "$POLICIES_DIR/{def_name}.json" <<\'POLICYEOF\'')
                lines.append(json.dumps(policy_json, indent=2, ensure_ascii=False))
                lines.append("POLICYEOF")
                lines.append(f"az policy definition create --name {def_name} \\")
                lines.append(f'  --mode Indexed --rules "$POLICIES_DIR/{def_name}.json" --only-show-errors')
                lines.append(f"az policy assignment create --name {def_name} \\")
                lines.append(f'  --scope "$SCOPE" --policy {def_name} --only-show-errors')
                lines.append("")

        # 5. Tarefas de Remediação (Remediation Tasks)
        lines.append("# ------------------------------------------------------------------------------")
        lines.append("# 5. Tarefas de Remediação para Recursos e RGs Existentes")
        lines.append("# ------------------------------------------------------------------------------")
        for i in range(1, len(rgs_exact) + 1):
            name = f"openfinops-rg-{slug_code}-{i}"
            lines.append(f"az policy remediation create --name remediate-{name} \\")
            lines.append(f'  --policy-assignment {name} --resource-discovery-mode ReEvaluateCompliance --only-show-errors || true')
        for i in range(1, len(rgs_patterns) + 1):
            name = f"openfinops-rgpat-{slug_code}-{i}"
            lines.append(f"az policy remediation create --name remediate-{name} \\")
            lines.append(f'  --policy-assignment {name} --resource-discovery-mode ReEvaluateCompliance --only-show-errors || true')
        for i in range(1, len(res_patterns) + 1):
            name = f"openfinops-respat-{slug_code}-{i}"
            lines.append(f"az policy remediation create --name remediate-{name} \\")
            lines.append(f'  --policy-assignment {name} --resource-discovery-mode ReEvaluateCompliance --only-show-errors || true')
        lines.append("")

    lines.append('echo "[INFO] Implantação de políticas do OpenFinops concluída com sucesso!"')
    lines.append("")

    return "\n".join(lines)


def _build_policy_definition(
    display_name: str,
    description: str,
    if_condition: dict,
    tags: dict[str, str],
) -> dict:
    operations = [
        {"operation": "addOrReplace", "field": f"tags['{k}']", "value": v}
        for k, v in tags.items() if v
    ]
    return {
        "mode": "Indexed",
        "displayName": display_name,
        "description": description,
        "policyRule": {
            "if": if_condition,
            "then": {
                "effect": "modify",
                "details": {
                    "roleDefinitionIds": [
                        "/providers/microsoft.authorization/roleDefinitions/b24988ac-6180-42a0-ab88-20f7382dd24c",
                        "/providers/microsoft.authorization/roleDefinitions/4a9ae827-6dc8-4573-8ac7-8239d42aa03f",
                    ],
                    "operations": operations,
                },
            },
        },
    }
